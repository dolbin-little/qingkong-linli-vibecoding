const {chromium}=require('playwright');
const fs=require('fs');
(async()=>{
 const browser=await chromium.launch({headless:true,channel:process.env.BROWSER_CHANNEL||'msedge'});
 const context=await browser.newContext({viewport:{width:1600,height:1000}});
 const page=await context.newPage(),errors=[],checks=[];
 page.on('pageerror',e=>errors.push(e.message));
 const check=(ok,label)=>{if(!ok)throw Error(label);checks.push(label)};
 await page.goto('http://127.0.0.1:19051/');
 await page.locator('#password').fill('GreenFlight2026!');
 await page.locator('#login-form button').click();
 await page.waitForFunction(()=>!document.querySelector('#login').open);
 await page.locator('#order').selectOption('LH-DEMO-002');
 await page.locator('[data-cmd="preview_order"]').click();
 await page.waitForFunction(()=>document.querySelector('#order-preview').textContent.includes('建议'));
 check((await page.locator('#order-preview').textContent()).includes('Wh'),'Order candidate plan displayed');
 await page.locator('[data-cmd="lease"]').click();
 await page.waitForFunction(()=>document.querySelector('#lease').textContent.includes('网页'));
 await page.locator('[data-cmd="load"]').click();
 await page.waitForFunction(()=>document.querySelector('#phase').textContent==='任务就绪');
 await page.waitForFunction(()=>document.querySelector('#task-list').textContent.includes('已预占'));
 check(await page.locator('[data-cmd="load"]').isDisabled(),'Loaded task cannot be loaded again from button');
 check((await page.locator('#task-list').textContent()).includes('已预占'),'Reservation visible in task history');
 check(await page.locator('#order').inputValue()==='LH-DEMO-002','Current order remains selected');
 await page.locator('#view2d').click();
 await page.evaluate(()=>window.scrollTo(0,0));
 await page.screenshot({path:'reports/web-order-ready.png',fullPage:true});
 await page.locator('[data-task-cancel]').click();
 await page.waitForFunction(()=>document.querySelector('#operation-message').textContent.includes('已释放'));
 check((await page.locator('#task-list').textContent()).includes('已释放返库'),'Cancellation releases resources visibly');
 await page.locator('nav [data-page="safety"]').click();
 await page.locator('[data-cmd="release"]').click();
 const c=await context.newPage();await c.goto('http://127.0.0.1:19051/community');
 await c.waitForTimeout(1000);
 await c.getByText('订单管理',{exact:true}).click();
 await c.waitForTimeout(500);
 check(await c.locator('a[href^="/?order="]').count()>0,'Business orders expose flight entry');
 check(errors.length===0,'No JavaScript page errors');
 fs.writeFileSync('reports/business-ui-check.json',JSON.stringify({checks,errors},null,2));
 console.log(JSON.stringify({checks,errors}));await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
